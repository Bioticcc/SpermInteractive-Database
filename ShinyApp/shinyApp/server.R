        withProgress(message = "Loading RA lineplot data…", value = 0, {
          get_ra_line_mean()
          incProgress(1)
        })
      } else {
        get_ra_line_mean()
      }
      ra_assets_ready$line <- TRUE
    }
    genes <- get_interactive_genes()
    update_ra_line_inputs(genes)
    TRUE
  }

