  minmax01 <- function(x) {
    rng <- range(x, na.rm = TRUE)
    if (!is.finite(rng[1]) || !is.finite(rng[2]) || rng[1] == rng[2]) {
      return(rep(1, length(x)))  # flat case → treat as max shade
    }
    (x - rng[1]) / (rng[2] - rng[1])
  }
  
  
