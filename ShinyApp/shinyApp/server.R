      cols,
      as.numeric(expr_vals),
      seq_along(match_ids),
      scaled
    )
    
    payload <- unname(payload)
    
    
    #DEBUG
    cat(sprintf("[server] heatmap-colorize: n=%d | sample colors=%s\n",
                length(payload),
                paste(head(vapply(payload, function(p) p$color, ""), 5), collapse=", ")))
